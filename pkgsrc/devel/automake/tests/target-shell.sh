# A cross build of automake records /bin/sh, not the build-host CONFIG_SHELL,
# in the SHELL assignment configure writes into bin/automake.
# Usage: target-shell.sh BMAKE
set -eu
[ "$#" -eq 1 ] || { echo "Usage: $0 BMAKE" >&2; exit 2; }
bmake=$1
dir=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
fail() { echo "FAIL: $*" >&2; exit 1; }
scratch=$(mktemp -d "${TMPDIR:-/tmp}/automake-target-shell.XXXXXX")
trap 'rm -rf "$scratch"' EXIT INT TERM
# The cross branch of the recipe, without the pkgsrc infrastructure.
awk '/^\.if \$\{USE_CROSS_COMPILE:Uno:tl\} == "yes"$/ {p=1; next}
    p && /^\.else$/ {exit} p && /^SUBST_/ {print}' "$dir/Makefile" > "$scratch/subst.mk"
q() { "$bmake" -f "$scratch/subst.mk" CONFIG_SHELL=/host/bin/mksh -V "\${$1}"; }
case " $(q SUBST_CLASSES) " in *' target-sh '*) ;; *) fail 'no target shell substitution in cross builds' ;; esac
[ "$(q SUBST_FILES.target-sh)" = bin/automake ] || fail 'the substitution misses bin/automake'
[ "$(q SUBST_STAGE.target-sh)" = post-build ] || fail 'bin/automake is generated by the build'
# The line configure generates from bin/automake.in (@SHELL@ = CONFIG_SHELL).
printf "%s\n" "  \$ENV{'SHELL'} = '/host/bin/mksh' if exists \$ENV{'DJDIR'};" > "$scratch/automake"
eval "sed $(q SUBST_SED.target-sh)" < "$scratch/automake" > "$scratch/out"
[ "$(cat "$scratch/out")" = "  \$ENV{'SHELL'} = '/bin/sh' if exists \$ENV{'DJDIR'};" ] ||
    fail 'bin/automake keeps the build-host shell'
echo 'PASS: cross automake records the target shell'
