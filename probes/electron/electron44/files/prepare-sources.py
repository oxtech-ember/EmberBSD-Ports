"""Prepare Electron's pinned DEPS input; do not sync or execute its hooks."""

import argparse
import ast
from pathlib import Path
import subprocess
import sys

ELECTRON_URL = "https://github.com/electron/electron.git"
ELECTRON_REVISION = "45d20ec03000aac41e73b2abdb707936b4f98ed0"
CHROMIUM_URL = "https://chromium.googlesource.com/chromium/src.git"
CHROMIUM_VERSION = "156.0.8078.49"
CHROMIUM_REVISION = "29eb03535d5f2f4f899b95f22a92413ffde5284e"
NODE_URL = "https://github.com/nodejs/node.git"
NODE_BEFORE = "v24.22.1"
NODE_VERSION = "v24.22.1"
NODE_REVISION = "ce7aaf1cee78b8cf0ce17364260535c418d3ed26"
# Electron 45.1.0 already contains the current Node security roll.
PATCHES = ()


def require(condition, message):
    if not condition:
        raise ValueError(message)


def git_run(git, root, *args, env=None):
    result = subprocess.run([str(git), "-C", str(root), *args],
                            capture_output=True, text=True, env=env)
    require(result.returncode == 0,
            f"git {args[0]} failed: {result.stderr.strip()}")
    return result.stdout.strip()


def assignment(tree, name):
    values = [node.value for node in tree.body if isinstance(node, ast.Assign)
              and any(isinstance(target, ast.Name) and target.id == name
                      for target in node.targets)]
    require(len(values) == 1, f"DEPS must assign {name} exactly once")
    return values[0]


def dict_item(node, key):
    require(isinstance(node, ast.Dict), "DEPS mapping must be a literal dict")
    values = [value for item, value in zip(node.keys, node.values)
              if isinstance(item, ast.Constant) and item.value == key]
    require(len(values) == 1, f"DEPS must contain {key} exactly once")
    return values[0]


def deps_string(node, variables):
    if isinstance(node, ast.Constant) and isinstance(node.value, str):
        return node.value
    if isinstance(node, ast.BinOp) and isinstance(node.op, ast.Add):
        return deps_string(node.left, variables) + deps_string(node.right, variables)
    if (isinstance(node, ast.Call) and isinstance(node.func, ast.Name)
            and node.func.id == "Var" and len(node.args) == 1 and not node.keywords):
        key = ast.literal_eval(node.args[0])
        value = variables.get(key)
        require(isinstance(value, str), f"unsupported DEPS Var({key!r})")
        return value
    raise ValueError("unsupported DEPS URL expression")


def check_deps(path, node_version):
    # DEPS is executable Python. Inspect only the pinned literal assignments;
    # do not execute upstream code during this source-only preparation step.
    tree = ast.parse(path.read_text(encoding="utf-8"), filename=str(path))
    variables = ast.literal_eval(assignment(tree, "vars"))
    require(isinstance(variables, dict), "DEPS vars must be a literal dict")
    expected = {"chromium_version": CHROMIUM_VERSION, "node_version": node_version}
    for key, value in expected.items():
        require(variables.get(key) == value, f"DEPS {key} does not match {value}")
    deps = assignment(tree, "deps")
    for name, url in (("src", CHROMIUM_URL + "@" + CHROMIUM_VERSION),
                      ("src/third_party/electron_node", NODE_URL + "@" + node_version)):
        value = deps_string(dict_item(dict_item(deps, name), "url"), variables)
        require(value == url, f"DEPS {name} URL does not match its pin")


def gclient_config(target_cpu):
    require(target_cpu in ("arm64", "x64"), "unsupported target CPU")
    solution = {
        "name": "src/electron", "url": ELECTRON_URL,
        "deps_file": "DEPS", "managed": False, "custom_deps": {},
        "custom_vars": {
            "chromium_version": CHROMIUM_REVISION,
            "node_version": NODE_REVISION,
            # Disable Electron's legacy sysroot hooks. Chromium also has GCS
            # sysroot dependencies; source-sync integration must handle those.
            "install_sysroot": False,
        },
    }
    return ("# Generated by the Electron Ports source preparer.\n"
            f"solutions = {[solution]!r}\n"
            "target_os = ['linux']\n"
            f"target_cpu = {[target_cpu]!r}\n")


def ordered_patches(patch_dir):
    patch_dir = Path(patch_dir)
    # Git does not preserve an empty patch directory when a roll lands upstream.
    if not PATCHES and not patch_dir.exists():
        return []
    patch_dir = patch_dir.resolve(strict=True)
    require(patch_dir.is_dir(), "recipe patch path must be a directory")
    patches = [patch_dir / name for name in PATCHES]
    require(all(path.is_file() for path in patches), "recipe patch is missing")
    require(len(set(PATCHES)) == len(PATCHES), "recipe patch order contains a duplicate")
    require(set(PATCHES) == {path.name for path in patch_dir.glob("patch-*")},
            "recipe patch order does not cover the complete patch directory")
    return patches


def prepare(source, destination, git, target_cpu, patch_dir):
    source = Path(source).resolve(strict=True)
    git = Path(git)
    require(git.is_absolute() and git.is_file(), "--git must name an absolute executable")
    destination = Path(destination).absolute()
    require(not destination.exists() and not destination.is_symlink(),
            "destination already exists; use a new work directory")
    parent = destination.parent.resolve(strict=True)
    destination = parent / destination.name
    require(not destination.is_relative_to(source), "destination must be outside source")
    root = git_run(git, source, "rev-parse", "--show-toplevel")
    require(Path(root).resolve() == source, "source must be the Electron repository root")
    require(git_run(git, source, "rev-parse", "HEAD") == ELECTRON_REVISION,
            "Electron HEAD does not match the recipe pin")
    require(not git_run(git, source, "status", "--porcelain", "--untracked-files=all"),
            "Electron source must be clean, including untracked files")
    check_deps(source / "DEPS", NODE_BEFORE)
    config = gclient_config(target_cpu)
    patches = ordered_patches(patch_dir)

    # Exclusive creation refuses an existing or concurrently created workspace.
    # The caller holds its normal source lock. Retain partial work on failure;
    # never reset or remove a caller's source directory.
    destination.mkdir()
    electron = destination / "src/electron"
    electron.parent.mkdir()
    git_run(git, destination, "clone", "--no-hardlinks", "--dissociate",
            "--no-checkout", str(source), str(electron))
    git_run(git, electron, "checkout", "--detach", ELECTRON_REVISION)
    # Do not retain a private local source path as the checkout's remote.
    git_run(git, electron, "remote", "set-url", "origin", ELECTRON_URL)
    for patch in patches:
        git_run(git, electron, "apply", "--check", "--index", str(patch))
        git_run(git, electron, "apply", "--index", str(patch))
    check_deps(electron / "DEPS", NODE_VERSION)
    # This final file is absent when preparation fails before completion.
    (destination / ".gclient").write_text(config, encoding="utf-8")
    return electron


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--electron-source", required=True, type=Path,
                        help="clean checkout at the recipe's Electron pin")
    parser.add_argument("--destination", required=True, type=Path,
                        help="new gclient workspace; parent must exist")
    parser.add_argument("--git", required=True, type=Path,
                        help="explicit Git executable used only for source preparation")
    parser.add_argument("--target-cpu", required=True, choices=("arm64", "x64"))
    args = parser.parse_args()
    try:
        root = prepare(args.electron_source, args.destination, args.git,
                       args.target_cpu, Path(__file__).resolve().parents[1] / "patches")
    except (ValueError, OSError, SyntaxError) as exc:
        parser.exit(1, f"source preparation failed: {exc}\n")
    print(f"Prepared Electron DEPS input: {root}")
    print("Chromium dependency sync, upstream hooks and BSD overlays have not run.")


if __name__ == "__main__":
    main()
