set -eu
if [ "$#" -ne 3 ]; then
    echo "Usage: $0 BASELINE_PROTOC PATCHED_PROTOC NEW_OUTPUT_DIRECTORY" >&2
    exit 2
fi
baseline=$1
patched=$2
output=$3
probe=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
[ -x "$baseline" ] && [ -x "$patched" ]
[ ! -e "$output" ] || { echo "Use a new output directory" >&2; exit 2; }
mkdir -p "$output/baseline" "$output/patched"
"$baseline" --version > "$output/baseline-version.txt"
"$patched" --version > "$output/patched-version.txt"
cmp "$output/baseline-version.txt" "$output/patched-version.txt"
grep -qx 'libprotoc 36.2' "$output/patched-version.txt"
"$baseline" --cpp_out="$output/baseline" -I "$probe" "$probe/contract.proto"
"$patched" --cpp_out="$output/patched" -I "$probe" "$probe/contract.proto"
cmp "$output/baseline/contract.pb.cc" "$output/patched/contract.pb.cc"
cmp "$output/baseline/contract.pb.h" "$output/patched/contract.pb.h"
set +e
"$baseline" --emberbsd-unknown-option > "$output/baseline-error.txt" 2>&1
baseline_status=$?
"$patched" --emberbsd-unknown-option > "$output/patched-error.txt" 2>&1
patched_status=$?
set -e
[ "$baseline_status" -ne 0 ] && [ "$baseline_status" -eq "$patched_status" ]
cmp "$output/baseline-error.txt" "$output/patched-error.txt"
echo "PASS: protoc generated bytes and CLI error behavior agree"
